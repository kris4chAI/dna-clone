"""snowskills: deterministic, Snowflake-interoperable generators behind the delivery skills.

Every delivery skill (e.g. /gen-grants, /reconcile) is a function that takes a dict of
parameters and returns generated artefacts: Snowflake SQL, schemachange scripts, dbt models,
Terraform, GitHub Actions workflows, YAML specs and Markdown runbooks.

Generators never connect to Snowflake. Apply the SQL they emit with `snow sql -f <file>`
(Snowflake CLI) or schemachange after human review, or through the Navigator app's
"Execute on Snowflake" action when a connection is configured.

    python -m snowskills list
    python -m snowskills run gen-grants --params params.json --out ./out
"""
from __future__ import annotations

import csv
import io
import re
from dataclasses import dataclass, field
from typing import Callable

REGISTRY: dict[str, "Skill"] = {}


@dataclass
class Field:
    key: str
    label: str
    kind: str = "text"            # text | textarea | lines | table | choice | number
    default: str = ""
    help: str = ""
    options: list[str] = field(default_factory=list)


@dataclass
class Skill:
    name: str                     # slash command without the slash, e.g. "gen-grants"
    stage: str                    # implementation stage code (discover, design, ...)
    agent: str
    title: str
    description: str
    snowflake: list[str]          # Snowflake features the output uses
    fields: list[Field]
    steps: list[str]              # how an agent should use the skill (goes into SKILL.md)
    gate: str                     # the human check before anything is applied
    fn: Callable = None

    @property
    def package(self) -> str:
        return f"sf-{self.name}"

    def defaults(self) -> dict:
        return {f.key: f.default for f in self.fields}


def skill(**meta):
    def deco(fn):
        s = Skill(fn=fn, **meta)
        REGISTRY[s.name] = s
        return fn
    return deco


class P:
    """Typed access to raw form/CLI parameters."""

    def __init__(self, raw: dict, sk: Skill):
        self.raw = {**sk.defaults(), **{k: v for k, v in (raw or {}).items() if v not in (None, "")}}

    def s(self, k, default=""):
        v = self.raw.get(k, default)
        return v.strip() if isinstance(v, str) else v

    def n(self, k, default=0):
        try:
            return float(self.s(k, default))
        except (TypeError, ValueError):
            return default

    def lines(self, k):
        v = self.raw.get(k, "")
        if isinstance(v, list):
            return [str(x).strip() for x in v if str(x).strip()]
        return [x.strip() for x in str(v).splitlines() if x.strip() and not x.strip().startswith("#")]

    def table(self, k) -> list[dict]:
        v = self.raw.get(k, "")
        if isinstance(v, list):
            return v
        rows = list(csv.DictReader(io.StringIO("\n".join(self.lines(k))), skipinitialspace=True))
        return [{(kk or "").strip(): (vv or "").strip() for kk, vv in r.items()} for r in rows]


def ident(s: str) -> str:
    """Snowflake-safe unquoted identifier (upper case)."""
    s = re.sub(r"[^A-Za-z0-9_$.]", "_", (s or "").strip()).strip("_")
    return (s or "UNNAMED").upper()


def lit(s: str) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def to_yaml(obj, indent=0) -> str:
    """Minimal YAML emitter (dict/list/scalar) so skills have no dependencies."""
    pad = "  " * indent
    out = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, (dict, list)) and v:
                out.append(f"{pad}{k}:")
                out.append(to_yaml(v, indent + 1))
            else:
                out.append(f"{pad}{k}: {_scalar(v)}")
    elif isinstance(obj, list):
        for v in obj:
            if isinstance(v, dict) and v:
                first = True
                for line in to_yaml(v, indent + 1).splitlines():
                    out.append(f"{pad}- {line.strip()}" if first else line)
                    first = False
            else:
                out.append(f"{pad}- {_scalar(v)}")
    else:
        out.append(pad + _scalar(obj))
    return "\n".join(out)


def _scalar(v):
    if v is None or v == {} or v == []:
        return "[]" if v == [] else ("{}" if v == {} else "null")
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    return f'"{s}"' if re.search(r"[:#\[\]{},&*!|>'\"%@`]|^\s|\s$|^$", s) else s


def header(sk: Skill, what: str) -> str:
    return (f"-- Generated by {sk.package} (/{sk.name}) · {what}\n"
            f"-- Review before applying: {sk.gate}\n"
            f"-- Apply with: snow sql -f <this file> -c <connection>   (or commit as a schemachange script)\n\n")


def run(name: str, params: dict | None = None) -> dict:
    sk = REGISTRY[name]
    out = sk.fn(P(params, sk), sk)
    out.setdefault("notes", [])
    out.setdefault("summary", "")
    return out


